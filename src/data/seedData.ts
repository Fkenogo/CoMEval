export function createInitialSeedState(): MealState {
  const reportNarratives: Record<string, Record<string, string>> = {};
  for (const proj of Object.values(projects)) {
    for (const tpl of proj.reportTemplates) {
      const key = `${proj.id}::${tpl.id}`;
      reportNarratives[key] = {};
      for (const sec of tpl.defaultSections) {
        reportNarratives[key][sec.id] = sec.body;
      }
    }
  }

  return {
    activeProjectId: 'childfund-uganda',
    activeModule: 'portfolio',
    activeRole: 'programme_manager',
    filters: {
      period: 'all',
      partner: 'all',
      location: 'all',
      sector: 'all',
    },
    projects,
    documents,
    commitments,
    activities,
    deliveryRecords,
    registers,
    registerRows,
    resultsNodes,
    indicators,
    observations,
    surveyInstruments,
    surveyResults,
    correctiveActions,
    learningEntries,
    evaluationQuestions,
    evaluatorFindings,
    handoverSnapshots,
    reportNarratives,
    walkthroughOpen: false,
    activeWalkthroughTab: 'childfund',
  };
}
